export const COLOMBIA_DEPARTMENTS = Object.keys(COLOMBIA_LOCATION_DATA).sort((a, b) => {
  if (a === 'Bogotá D.C.') return -1
  if (b === 'Bogotá D.C.') return 1
  return a.localeCompare(b, 'es')
})

export function getCitiesForDepartment(departmentName: string): string[] {
  if (!departmentName) return []
  return COLOMBIA_LOCATION_DATA[departmentName] || []
}

export function searchDepartments(query: string): string[] {
  if (!query) return COLOMBIA_DEPARTMENTS
  const clean = query.trim().toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '')
  return COLOMBIA_DEPARTMENTS.filter(dept => {
    const norm = dept.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    return norm.includes(clean)
  })
}

export function searchCities(departmentName: string, query: string): string[] {
  const cities = getCitiesForDepartment(departmentName)
  if (!query) return cities
  const clean = query.trim().toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '')
  return cities.filter(city => {
    const norm = city.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    return norm.includes(clean)
  })
}
